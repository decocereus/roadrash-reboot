def wheel(name, R, w, rimR, z, rear):
    c = (0, R, z)
    parts = []
    bm = bmesh.new()
    prof = []
    for i in range(15):
        a = math.radians(-96 + 192 * i / 14)
        prof.append((rimR + (R - rimR) * max(0.0, math.cos(a * 0.92)) ** 0.5, w / 2 * math.sin(a)))
    lathe(bm, c, prof, "tyre", steps=44)
    parts.append(finish(name + "_tyre", bm, angle=70))
    bm = bmesh.new()
    wr = w * 0.46
    lathe(bm, c, [(rimR + 0.008, -wr), (rimR + 0.008, wr), (rimR - 0.02, wr), (rimR - 0.032, wr * 0.35), (rimR - 0.032, -wr * 0.35), (rimR - 0.02, -wr)], "accent", steps=44, closed=True)
    for s in range(5):
        for off in (-0.2, 0.2):
            a0 = s * math.tau / 5 + off
            a1 = s * math.tau / 5 - off * 0.4
            p0 = (0, R + 0.05 * math.cos(a0), z + 0.05 * math.sin(a0))
            p1 = (0, R + (rimR - 0.024) * math.cos(a1), z + (rimR - 0.024) * math.sin(a1))
            tube(bm, [p0, p1], [(0.02, 0.014), (0.012, 0.011)], "accent", n=4, up=(1, 0, 0), phase=math.pi / 4)
    lathe(bm, c, [(0.0, -w * 0.42), (0.058, -w * 0.42), (0.058, w * 0.42), (0.0, w * 0.42)], "dark", steps=16)
    parts.append(finish(name + "_rim", bm, angle=30, bevel=0.003))
    bm = bmesh.new()
    for s in ([1] if rear else [-1, 1]):
        x = s * (w / 2 + 0.018)
        r = 0.11 if rear else 0.15
        lathe(bm, (x, R, z), [(r - 0.045, -0.003), (r, -0.003), (r, 0.003), (r - 0.045, 0.003)], "metal", steps=32, closed=True)
        lathe(bm, (x, R, z), [(0.0, -0.004), (r - 0.05, -0.004), (r - 0.05, 0.004), (0.0, 0.004)], "dark", steps=10)
    if rear:
        lathe(bm, (-(w / 2 + 0.022), R, z), [(0.03, -0.004), (0.105, -0.004), (0.105, 0.004), (0.03, 0.004)], "dark", steps=24, closed=True)
    parts.append(finish(name + "_disc", bm, angle=30))
    return join(name, parts)


