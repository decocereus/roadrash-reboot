def front_hull(bm, rings, material):
    vertices=[[bm.verts.new(B(*point)) for point in ring] for ring in rings]
    for left,right in zip(vertices,vertices[1:]):
        for i in range(len(left)):
            j=(i+1)%len(left)
            face=bm.faces.new((left[i],left[j],right[j],right[i]))
            face.material_index=MI[material]
    for ring in (vertices[0],vertices[-1]):
        face=bm.faces.new(ring);face.material_index=MI[material]


